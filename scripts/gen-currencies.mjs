// Generates src/currencies.ts from the ISO 4217 list published by SIX.
// Usage: node scripts/gen-currencies.mjs [path-to-list-one.xml]
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE =
    "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml";
const xml = process.argv[2]
    ? readFileSync(process.argv[2], "utf8")
    : await (await fetch(SOURCE)).text();

const published = /Pblshd="([^"]+)"/.exec(xml)?.[1] ?? "unknown";
const units = new Map();
for (const [, entry] of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
    const code = /<Ccy>([A-Z]{3})<\/Ccy>/.exec(entry)?.[1];
    const minor = /<CcyMnrUnts>(\d+)<\/CcyMnrUnts>/.exec(entry)?.[1];
    if (code && minor !== undefined) units.set(code, Number(minor));
}
const rows = [...units].sort(([a], [b]) => a.localeCompare(b));
writeFileSync(
    new URL("../src/currencies.ts", import.meta.url),
    `// Generated by scripts/gen-currencies.mjs from ISO 4217 list one (published ${published}). Do not edit.\n` +
        `export const MINOR_UNITS: Readonly<Record<string, number>> = {\n` +
        rows.map(([c, n]) => `    ${c}: ${n},`).join("\n") +
        `\n};\n`,
);
console.log(`wrote ${rows.length} currencies (ISO 4217 published ${published})`);
