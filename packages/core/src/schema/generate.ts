/**
 * Generators over `shapes.ts`: the JSON Schema that other languages read, and
 * the Convex validators the Convex component uses. `pnpm gen` writes both;
 * tests fail when a written file differs from what these return.
 */
import { jsonSchema, type Node } from "./dsl.ts";
import { shapes } from "./shapes.ts";

export const SCHEMA_ID = "https://github.com/cynco-labs/invoice-primitives/schema/invoice-primitives.schema.json";

export function schemaJson(): string {
    return `${JSON.stringify(jsonSchema(SCHEMA_ID, shapes), null, 2)}\n`;
}

/** Convex validators (`v.*`) for every named shape, each `v<Name>`, defined before use. */
export function convexValidators(): string {
    const defined = new Set<string>();
    const out: string[] = [];
    const expr = (node: Node): string => {
        switch (node.kind) {
            case "named":
                define(node);
                return `v${node.name}`;
            case "string":
                return "v.string()";
            case "number":
                return "v.number()";
            case "boolean":
                return "v.boolean()";
            case "literal":
                return `v.literal(${JSON.stringify(node.value)})`;
            case "array":
                return `v.array(${expr(node.item)})`;
            case "record":
                return `v.record(v.string(), ${expr(node.value)})`;
            case "object": {
                const fields = Object.entries(node.fields)
                    .filter(([, f]) => f.presence !== "absent")
                    .map(([k, f]) => `${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${f.presence === "optional" ? `v.optional(${expr(f.node)})` : expr(f.node)}`);
                return `v.object({ ${fields.join(", ")} })`;
            }
            case "union":
                return `v.union(${node.options.map(expr).join(", ")})`;
        }
    };
    const define = (node: Extract<Node, { kind: "named" }>) => {
        if (defined.has(node.name)) return;
        defined.add(node.name);
        const body = expr(node.node);
        out.push(`/** ${node.description} */\nexport const v${node.name} = ${body};\n`);
    };
    for (const s of shapes) expr(s.node);
    return [
        "// Generated by `pnpm gen` from @invoice-primitives/core's schema/shapes.ts. Do not edit.",
        'import { v } from "convex/values";',
        "",
        ...out,
    ].join("\n");
}
